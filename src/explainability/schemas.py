"""Pydantic schemas for the explainability API (Phase 7).

Structured representation of feature-level attributions and human-readable
summaries generated by the explainability engine.
"""

from typing import Literal
from pydantic import BaseModel, ConfigDict, Field


class FeatureContribution(BaseModel):
    """Contribution of an individual feature to the model's output in log-odds space."""

    model_config = ConfigDict(extra="forbid")

    feature: str = Field(description="Name of the input feature")
    feature_value: float = Field(description="Original value of the feature in the submitted transaction")
    contribution: float = Field(
        description="Feature contribution in log-odds space (positive = towards fraud, negative = towards legitimate)"
    )
    direction: Literal["TOWARDS_FRAUD", "TOWARDS_LEGITIMATE"] = Field(
        description="Whether this feature pushed the prediction towards fraud or legitimate"
    )


class ExplanationResponse(BaseModel):
    """Complete explanation response for a transaction."""

    model_config = ConfigDict(extra="forbid")

    prediction: Literal[0, 1] = Field(description="Model prediction: 0 = legitimate, 1 = fraud")
    probability: float = Field(ge=0.0, le=1.0, description="Model probability of fraud (class 1)")
    fraud_probability: float = Field(ge=0.0, le=1.0, description="Model probability of fraud (class 1)")
    explainer: str = Field(default="SHAP LinearExplainer", description="Explainability method used")
    explanation_space: str = Field(
        default="log_odds",
        description="Mathematical output space of feature contributions (log-odds before logistic transform)",
    )
    base_value: float = Field(
        description="Expected model output (log-odds) over the background reference dataset"
    )
    top_features: list[FeatureContribution] = Field(
        description="Top contributing features ordered by descending absolute contribution"
    )
    summary: str = Field(description="Human-readable explanation of the prediction and influential features")
    explanation: str = Field(description="Human-readable explanation (identical to summary)")
